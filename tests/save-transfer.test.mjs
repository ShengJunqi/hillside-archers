import assert from 'node:assert/strict';
import {validSave} from '../dist/core.mjs';
import {encodeProgress, decodeProgress, mergeProgress} from '../dist/save-transfer.mjs';
let checks = 0;
const equal = (a, b, message) => {assert.deepEqual(a, b, message); checks++;};
const rejects = (fn, message) => {assert.throws(fn, Error, message); checks++;};
const progress = validSave({unlocked: true, checkpoint: 3, best: 24, targetBest: 2500, embers: 30, bow: 4, life: 5});
equal(decodeProgress(encodeProgress(progress)), progress, 'portable progress round-trips without losing unlocks');
equal(decodeProgress(' \n' + encodeProgress(progress) + '\n'), progress, 'chat whitespace is tolerated');
equal(decodeProgress(encodeProgress({...progress, accountToken: 'not-a-game-field', stats: {fire: 99}})), progress, 'export contains only permanent game progress');
for (const code of ['', 'HA1:anything', 'HA2:not base64', 'HA2:' + btoa('{}'), 'HA2:' + btoa('[]'), 'HA2:' + btoa(JSON.stringify({...progress, best: '24'})), 'HA2:' + 'x'.repeat(9000)]) rejects(() => decodeProgress(code), 'malformed imports are rejected');
const older = validSave({checkpoint: 1, best: 2, embers: 3, bow: 1});
equal(mergeProgress(progress, older), progress, 'older import cannot erase stronger local progress');
equal(mergeProgress(older, progress), progress, 'new origin acquires progression');
equal(mergeProgress(mergeProgress(older, progress), progress), progress, 'repeated import cannot duplicate currency');
const combined = mergeProgress(progress, {targetBest: 3000, bow: 5, life: 1, embers: 15});
equal(combined.targetBest, 3000, 'separate record is retained');
equal(combined.life, 5, 'stronger permanent training is retained');
console.log(checks + ' progress-transfer checks passed.');
